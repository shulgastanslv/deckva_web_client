export type CodeSyntax = {
  foreground: string;
  keyword: string;
  string: string;
  comment: string;
  number: string;
  function: string;
  punctuation: string;
  property: string;
  parameter: string;
};

export type CodeThemeDef = {
  id: string;
  label: string;
  background: { from: string; to: string };
  syntax: { light: CodeSyntax; dark: CodeSyntax };
};

function syn(partial: Partial<CodeSyntax> & Pick<CodeSyntax, "foreground">): CodeSyntax {
  const fg = partial.foreground;
  return {
    foreground: fg,
    keyword: partial.keyword ?? fg,
    string: partial.string ?? fg,
    comment: partial.comment ?? fg,
    number: partial.number ?? fg,
    function: partial.function ?? fg,
    punctuation: partial.punctuation ?? fg,
    property: partial.property ?? fg,
    parameter: partial.parameter ?? fg,
  };
}

