export type CodeThemeId = (typeof CODE_THEMES)[number]["id"];

const LEGACY_THEME: Record<string, CodeThemeId> = {
  ray: "breeze",
  dark: "mono",
  light: "ice",
};

export function resolveThemeId(raw: string | undefined | null): CodeThemeId {
  if (raw && CODE_THEMES.some((t) => t.id === raw)) return raw as CodeThemeId;
  if (raw && LEGACY_THEME[raw]) return LEGACY_THEME[raw]!;
  return "breeze";
}

export function themeById(id: string): CodeThemeDef {
  return CODE_THEMES.find((t) => t.id === id) ?? CODE_THEMES[0]!;
}

export function themeSyntax(theme: CodeThemeDef, darkMode: boolean): CodeSyntax {
  return darkMode ? theme.syntax.dark : theme.syntax.light;
}
